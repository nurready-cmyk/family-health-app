def _status_is(values: dict[str, str], gender: str, key: str, expected_status: str) -> bool:
    raw_value = values.get(key)
    if raw_value is None:
        return False
    try:
        result = check_norm(key, float(raw_value), gender)
    except ValueError:
        return False
    return result is not None and result.status == expected_status


def _pressure_high(values: dict[str, str], gender: str) -> bool:
    try:
        systolic = float(values["systolic"]) if values.get("systolic") is not None else None
    except ValueError:
        systolic = None
    try:
        diastolic = float(values["diastolic"]) if values.get("diastolic") is not None else None
    except ValueError:
        diastolic = None

    return (systolic is not None and systolic > 130) or (diastolic is not None and diastolic > 85)


