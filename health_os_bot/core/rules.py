@dataclass(frozen=True)
class Rule:
    id: str
    check: Callable[[dict[str, str], str], bool]
    severity: str  # 'danger' | 'warning'
    title: str
    problem: str
    eat: list[str]
    avoid: list[str]
    workout: str
