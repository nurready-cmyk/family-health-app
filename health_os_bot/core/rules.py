def get_active_recommendations(values: dict[str, str], gender: str) -> list[Rule]:
    """Вернуть общие правила, сработавшие на текущих значениях показателей."""
    if not values:
        return []

    active = []
    for rule in RULES:
        try:
            if rule.check(values, gender):
                active.append(rule)
        except (TypeError, ValueError):
            continue
    return active

